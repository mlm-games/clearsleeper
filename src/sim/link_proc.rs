/// One player's process word and the mode word that came with it. The reference holds these on
/// the actor and writes them in one place, `commonProcInit`, which every transition in the game
/// funnels through: the reference has no other site that assigns the word.
#[derive(Resource, Debug, Clone, Copy, PartialEq, Eq)]
pub struct LinkProc {
    /// The process the player's own tick is running.
    pub current: Proc,
    /// The process the last transition left, which the reference reads at the top of its own
    /// init to decide what to tear down before the new one is stood up.
    pub previous: Proc,
    /// The mode word the init table carries for `current`.
    pub flags: u32,
    /// Ticks spent in `current`, the reference's per-process frame counter.
    pub frame: u32,
    /// True on the tick `current` was written, which is how a reader can tell a fresh transition
    /// from a settled process without comparing words.
    pub changed: bool,
}

impl Default for LinkProc {
    fn default() -> Self {
        Self::new(Proc::Wait)
    }
}

impl LinkProc {
    /// A word standing in `proc`, with the mode word the init table gives it.
    pub fn new(proc: Proc) -> Self {
        Self {
            current: proc,
            previous: proc,
            flags: proc.flags(),
            frame: 0,
            changed: true,
        }
    }

    /// The one place the process word changes: the reference's `commonProcInit` resets the frame
    /// counter and stamps the mode word on every transition, and leaves the previous word behind
    /// for its own exit work. Returns whether the word moved.
    pub fn set_proc(&mut self, proc: Proc) -> bool {
        if self.current == proc {
            return false;
        }
        self.previous = self.current;
        self.current = proc;
        self.flags = proc.flags();
        self.frame = 0;
        self.changed = true;
        true
    }

    /// Whether the process word may take `proc`, which is the guard set the reference's own
    /// process initialisers open with. Every one of them refuses the process it is already in,
    /// and the two slide initialisers refuse the other slide as well, because a slide already on
    /// the same polygon must run its own deceleration instead of restarting.
    pub fn can_enter(&self, proc: Proc) -> bool {
        if self.current == proc {
            return false;
        }
        !matches!(
            (proc, self.current),
            (Proc::SlideFront, Proc::SlideBack) | (Proc::SlideBack, Proc::SlideFront)
        )
    }

    /// `set_proc` behind [`LinkProc::can_enter`]: the guarded transition.
    pub fn enter(&mut self, proc: Proc) -> bool {
        if !self.can_enter(proc) {
            return false;
        }
        self.set_proc(proc);
        true
    }

    /// Retire the last tick: count it against the current process and drop the transition flag.
    /// A caller runs this before it makes any transition, so a word written during the tick is
    /// still flagged when the tick ends.
    pub fn advance(&mut self) {
        self.frame = self.frame.wrapping_add(1);
        self.changed = false;
    }

    /// Whether the current process carries a mode word bit, which is the reference's
    /// `checkModeFlg`.
    pub fn mode(&self, flag: u32) -> bool {
        self.flags & flag != 0
    }

    /// Whether the current process is one of `allowed`, which is the whole of a module's gate.
    pub fn permits(&self, allowed: &[Proc]) -> bool {
        allowed.contains(&self.current)
    }
}

/// Whether a module may act this tick. A world with no process word yet runs every module, the
/// same way a world with no stage collision still walks, so registering the word is the switch
/// that turns the gates on rather than the other way round.
pub fn allows(state: Option<&LinkProc>, allowed: &[Proc]) -> bool {
    state.map_or(true, |state| state.permits(allowed))
}

pub fn init(world: &mut World) {
    world.init_resource::<LinkProc>();
}
