/// `dCamParam_c::Change`: rows are indexed by `CamStyleId`, `NONE` has none.
pub fn style_by_id(id: i16) -> Option<&'static CamStyle> {
    usize::try_from(id).ok().and_then(|i| STYLES.get(i))
}

/// `dCamParam_c::Val`. Unknown tag or out-of-range index reads `0.0`; retail would read
/// past the row.
pub fn val(tag: [u8; 4], index: usize) -> f32 {
    style(tag).and_then(|s| s.params.get(index)).copied().unwrap_or(0.0)
}

/// `dCamParam_c::Val` against a style index rather than a tag.
pub fn val_by_id(id: i16, index: usize) -> f32 {
    style_by_id(id).and_then(|s| s.params.get(index)).copied().unwrap_or(0.0)
}

/// `dCamParam_c::Algorythmn`.
pub fn engine(tag: [u8; 4]) -> Option<CamEngine> {
    style(tag).map(|s| s.engine)
}

/// `dCamParam_c::Flag` / `CheckFlag`.
pub fn has_flag(tag: [u8; 4], mask: u16) -> bool {
    style(tag).is_some_and(|s| s.flag & mask != 0)
}
